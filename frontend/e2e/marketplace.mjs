// Marketplace v2 screens on the isolated stack: home, area picker, the three modes, "Quản lý tin".
import process from 'node:process'
import { Page, report, journey, check, php, data, sleep } from './lib.mjs'
const U = (key) => `c1-${key}@example.test`
const one = await Page.open(9351, 'browser-1')
const visible = (selector) => `(()=>{const e=document.querySelector(${JSON.stringify(selector)});return !!e && e.offsetParent !== null})()`

await journey('M1 home and area picker (guest)', async () => {
  // A profile reused from an earlier run may still be signed in.
  await one.call('Network.clearBrowserCookies')
  await one.goto('/', 2500)
  await one.evaluate('(localStorage.clear(), true)')
  await one.goto('/', 2500)
  await one.wait("document.querySelectorAll('[data-product]').length > 0", 'home feed has cards')
  check((await one.text('.home-hero h2')) === 'Đồ cũ giá tốt, gần bạn, chốt nhanh!', 'slogan')
  check((await one.evaluate("[...document.querySelectorAll('[data-home-tab]')].map(e=>e.innerText.trim()).join('|')")) === 'Dành cho bạn|Mới nhất|Video|Đấu giá', 'four tabs')
  check(await one.exists('.home-category'), 'category row')
  check(!(await one.exists('#area-dialog')), 'a guest is not interrupted by the area picker')
  await one.shot('M-home')
  for (const tab of ['latest', 'video', 'auction']) {
    await one.click(`[data-home-tab="${tab}"]`)
    await sleep(1500)
    check((await one.evaluate(`document.querySelector('[data-home-tab="${tab}"]').getAttribute('aria-pressed')`)) === 'true', 'tab ' + tab)
    await one.shot('M-home-' + tab)
  }
  await one.click('[data-home-tab="latest"]')
  await one.click('.home-hero [data-area-open]')
  await one.wait("!!document.querySelector('#area-dialog')", 'area dialog')
  check((await one.evaluate("document.querySelectorAll('.area-card').length")) === 3, 'three featured cities')
  check((await one.evaluate("document.querySelectorAll('.area-option').length")) === 35, '34 provinces plus "Toàn quốc"')
  await one.shot('M-area-dialog')
  await one.fill('#area-search', 'hà n')
  await sleep(300)
  check((await one.evaluate("[...document.querySelectorAll('.area-option')].some(e=>e.innerText.includes('Hà Nội'))")), 'search finds Hà Nội')
  await one.fill('#area-search', '')
  await one.evaluate("(document.querySelector('.area-card input[value=\"79\"]').click(), true)")
  await one.click('[data-area-confirm]')
  await one.wait("!document.querySelector('#area-dialog')", 'dialog closed')
  await one.wait("document.querySelector('.home-hero [data-area-open]').innerText.includes('Hồ Chí Minh')", 'button shows the chosen area')
  await sleep(1500)
  const names = await one.evaluate("[...document.querySelectorAll('.home-tabs [data-product] .product-card-area, [data-product] .product-card-area')].map(e=>e.innerText)")
  check(names.length > 0 && names.every((name) => name.includes('Hồ Chí Minh')), 'every card is from the chosen area: ' + names.slice(0, 3).join(' / '))
  await one.shot('M-home-area')
  // The choice survives a reload and reaches the listing page.
  await one.goto('/', 2500)
  check((await one.text('.home-hero [data-area-open]')).includes('Hồ Chí Minh'), 'area remembered')
  await one.fill('.home-hero input[type="search"]', 'C1 Demo')
  await one.submit('.home-hero form[role="search"]')
  await one.wait("location.pathname === '/products' && new URLSearchParams(location.search).get('province') === '79'", 'search keeps the area')
  await one.wait("document.querySelectorAll('[data-product]').length > 0", 'results')
  check(await one.evaluate(visible('.marketplace-compact')), 'compact header search on other pages')
  await one.shot('M-products-area')
})

await journey('M2 seller mode and "Quản lý tin"', async () => {
  await one.login(U('seller-1'))
  const id = data.users[U('seller-1')]
  // First visit after the welcome tour: the area picker opens by itself, once.
  await one.goto('/', 2500)
  await one.wait("!!document.querySelector('#area-dialog')", 'area picker opens once for a signed-in user')
  await one.click('[data-area-confirm]')
  await one.goto('/', 2500)
  check(!(await one.exists('#area-dialog')), 'area picker does not come back')
  check((await one.text('.mode-switcher-button')).includes('Dành cho người mua'), 'buyer mode on the home page')
  await one.click('.mode-switcher-button')
  check((await one.evaluate("[...document.querySelectorAll('[data-mode-option]')].map(e=>e.dataset.modeOption).join('|')")) === 'buyer|seller', 'a normal user is never offered admin')
  await one.shot('M-mode-buyer')
  await one.click('[data-mode-option="seller"]')
  check((await one.text('.mode-switcher-button')).includes('Dành cho người bán'), 'seller mode chosen')
  check((await one.evaluate(`localStorage.getItem('passlai:mode:${id}')`)) === 'seller', 'mode remembered per user')
  await one.shot('M-mode-seller')
  await one.clickText('Quản lý tin', '.mode-switcher-links')
  await one.wait("location.pathname === '/my-ads' && document.querySelectorAll('.my-ads-count').length === 7", 'my ads with counters')
  const expected = php(`$s = DB::table('shops')->where('owner_id', ${id})->value('id'); $c = fn ($st) => DB::table('products')->where('shop_id', $s)->whereNull('deleted_at')->where('status', $st)->count(); echo implode('|', array_map($c, ['ACTIVE', 'SOLD', 'REJECTED', 'DRAFT', 'PENDING', 'HIDDEN']));`)
  const shown = await one.evaluate("[...document.querySelectorAll('.my-ads-count')].map(e=>e.innerText.replace(/[()]/g,'')).join('|')")
  check(shown.split('|').slice(0, 6).join('|') === expected, `tab counters match the database: ${shown} vs ${expected}`)
  const active = Number(expected.split('|')[0])
  check(active > 0 && (await one.evaluate("document.querySelectorAll('[data-product]').length")) === Math.min(active, 20), 'active ads listed')
  check((await one.text('.my-ads-shop')).includes('C1 Demo'), 'shop name on the profile line')
  check((await one.text('.mode-switcher-button')).includes('Dành cho người bán'), 'seller mode follows the route')
  await one.shot('M-my-ads')
  await one.click('[data-tab="auction"]')
  await one.wait("new URLSearchParams(location.search).get('tab') === 'auction'", 'tab in the URL')
  await sleep(1200)
  const held = Number(shown.split('|')[6])
  check((await one.evaluate("document.querySelectorAll('[data-product]').length")) === held, 'auction tab lists the held products: ' + held)
  if (held) check((await one.evaluate("[...document.querySelectorAll('[data-product]')].every(e=>e.querySelector('[data-auction-lock]') && !e.querySelector('[data-action]'))")), 'held ads are locked')
  await one.shot('M-my-ads-auction')
  await one.fill('#my-ads-search', 'khong-co-tin-nao-nhu-the')
  await one.submit('.my-ads-search')
  await one.wait("!!document.querySelector('.my-ads-empty')", 'empty state')
  check((await one.text('.my-ads-empty h2')) === 'Không tìm thấy tin đăng' && (await one.exists('.my-ads-empty svg')) && (await one.text('.my-ads-empty [data-post]')) === 'Đăng tin', 'drawn empty state with "Đăng tin"')
  await one.shot('M-my-ads-empty')
  // The old address still works and a reload keeps the tab.
  await one.goto('/seller/products?tab=draft', 2500)
  await one.wait("location.pathname === '/my-ads' && new URLSearchParams(location.search).get('tab') === 'draft'", 'old route redirects')
  check((await one.evaluate("document.querySelector('[data-tab=\"draft\"]').getAttribute('aria-pressed')")) === 'true', 'draft tab restored')
  // Hide an active ad from the list, then show it again through the normal flow's first step.
  await one.goto('/my-ads', 2500)
  await one.wait("!!document.querySelector('[data-action=\"hide\"]')", 'an ad that can be hidden')
  const target = await one.evaluate("document.querySelector('[data-action=\"hide\"]').closest('[data-product]').dataset.product")
  await one.click(`[data-product="${target}"] [data-action="hide"]`)
  await one.wait(`!document.querySelector('[data-product="${target}"]')`, 'hidden ad leaves the active tab')
  check(php(`echo DB::table('products')->where('id', ${Number(target)})->value('status');`) === 'HIDDEN', 'ad is HIDDEN in the database')
  await one.wait(`document.querySelector('[data-tab="active"] .my-ads-count').innerText === '(${active - 1})'`, 'counter follows the action')
  await one.goto('/seller/dashboard', 2500)
  check((await one.text('.mode-switcher-button')).includes('Dành cho người bán'), 'seller shell carries the switcher')
  await one.shot('M-seller-shell')
})

await journey('M3 admin mode', async () => {
  await one.login(U('admin'))
  await one.evaluate(`(localStorage.setItem('passlai:first-time:${data.users[U('admin')]}:area','1'), true)`)
  await one.goto('/', 2500)
  await one.click('.mode-switcher-button')
  check((await one.evaluate("[...document.querySelectorAll('[data-mode-option]')].map(e=>e.dataset.modeOption).join('|')")) === 'buyer|seller|admin', 'admin sees three modes')
  await one.click('[data-mode-option="admin"]')
  check((await one.text('.mode-switcher-button')).includes('Quản trị'), 'admin mode chosen')
  await one.shot('M-mode-admin')
  const href = await one.evaluate("document.querySelector('.mode-switcher-links a').getAttribute('href')")
  check(href.startsWith('/admin'), 'admin shortcuts')
  await one.evaluate("(document.querySelector('.mode-switcher-links a').click(), true)")
  await one.wait("location.pathname.startsWith('/admin')", 'admin area')
  await sleep(1500)
  check((await one.evaluate("document.querySelector('.mode-switcher').dataset.mode")) === 'admin', 'admin shell carries the switcher')
  await one.shot('M-admin-shell')
  const shop = php(`echo DB::table('shops')->where('owner_id', ${data.users[U('seller-1')]})->value('id');`)
  // The list is paginated and now holds many shops: open this one's details directly.
  await one.goto(`/admin/shops?inspect=${shop}`, 2500)
  await one.wait("document.querySelector('main').innerText.includes('Khu vực: TP. Hồ Chí Minh')", 'admin sees the shop area')
  await one.shot('M-admin-shops')
  // Menu drawer and footer on the buyer side.
  await one.goto('/', 2500)
  await one.click('.marketplace-menu-toggle')
  await one.wait("!!document.querySelector('#nav-drawer')", 'drawer')
  await one.shot('M-drawer')
  await one.evaluate("(document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true})), true)")
  await one.goto('/help', 2000)
  check((await one.evaluate("document.querySelectorAll('footer a').length")) >= 8, 'footer links')
  await one.evaluate('(window.scrollTo(0, document.body.scrollHeight), true)')
  await one.shot('M-footer')
})
console.log(JSON.stringify({ journeys: report.journeys, overflow: Object.entries(report.shots).filter(([, v]) => v !== 'ok'), errors: report.errors }))
one.close()
process.exit(0)
