// "Quên mật khẩu" with a mailed temporary password, on the isolated stack (test database).
import process from 'node:process'
import { Page, report, journey, check, php, sleep } from './lib.mjs'
const one = await Page.open(9351, 'browser-1')
const BUYER = 'c1-buyer-b@example.test'

await journey('P1 forgot password mails a temporary password without touching the old one', async () => {
  await one.call('Network.clearBrowserCookies')
  php(`DB::table('users')->where('email', '${BUYER}')->update(['temporary_password' => null, 'temporary_password_expires_at' => null, 'must_change_password' => false]);`)
  const before = php(`echo DB::table('users')->where('email', '${BUYER}')->value('password');`)
  await one.goto('/forgot-password', 3500)
  check(!(await one.exists('.marketplace-header')), 'no pinned menu')
  await one.fill('#email', BUYER)
  await one.submit('.auth-form')
  await one.wait("!!document.querySelector('[role=status]')", 'generic confirmation')
  check((await one.text('[role=status]')).includes('mật khẩu tạm thời'), 'the page explains the temporary password')
  await one.shot('P-forgot-sent')
  check(php(`echo DB::table('users')->where('email', '${BUYER}')->whereNotNull('temporary_password')->where('temporary_password_expires_at', '>', now())->count();`) === '1', 'a hashed temporary password with an expiry is stored')
  check(php(`echo DB::table('users')->where('email', '${BUYER}')->value('password');`) === before, 'the old password is unchanged')
})

await journey('P2 signing in with it forces a new password, then the site opens again', async () => {
  await one.call('Network.clearBrowserCookies')
  // The mail itself is not readable here (array mailer): use a known temporary password instead.
  php(`DB::table('users')->where('email', '${BUYER}')->update(['temporary_password' => Hash::make('TamThoi12345'), 'temporary_password_expires_at' => now()->addHour(), 'must_change_password' => false]);`)
  await one.goto('/login', 3500)
  await one.fill('#auth-email', BUYER)
  await one.fill('#auth-password', 'TamThoi12345')
  await one.submit('.auth-form')
  await one.wait("location.pathname === '/account/password' && !!document.querySelector('[data-forced]')", 'sent to change the password')
  check(!(await one.exists('#change-current_password')), 'no current password asked for')
  await one.shot('P-change-forced')
  await one.goto('/orders', 2500)
  await one.wait("location.pathname === '/account/password'", 'other pages wait until the password is changed')
  await one.fill('#change-password', 'MatKhauMoi12345')
  await one.fill('#change-password_confirmation', 'MatKhauMoi12345')
  await one.submit('.change-password-card')
  await one.wait("location.pathname === '/orders'", 'back to where the user was going')
  check(php(`echo (int) DB::table('users')->where('email', '${BUYER}')->value('must_change_password');`) === '0', 'flag cleared')
  await one.call('Network.clearBrowserCookies')
  await one.goto('/login', 3500)
  await one.fill('#auth-email', BUYER)
  await one.fill('#auth-password', 'TamThoi12345')
  await one.submit('.auth-form')
  await sleep(1500)
  check(await one.exists('.auth-form .alert-danger'), 'the temporary password is used up')
  await one.fill('#auth-email', BUYER)
  await one.fill('#auth-password', 'MatKhauMoi12345')
  await one.submit('.auth-form')
  await one.wait("location.pathname !== '/login'", 'the new password signs in')
})
console.log(JSON.stringify({ journeys: report.journeys, overflow: Object.entries(report.shots).filter(([, v]) => v !== 'ok'), errors: report.errors }))
one.close()
process.exit(0)
