// E2E journeys A–H on the isolated stack. Usage: node run.mjs [A B ...]
import fs from 'node:fs/promises'
import process from 'node:process'
import { Page, data, journey, check } from './lib.mjs'
const only = process.argv.slice(2)
const want = (name) => !only.length || only.includes(name)
const U = (key) => `c1-${key}@example.test`
const product = (n) => data.products.find((p) => p.name.startsWith(`C1 Demo ${String(n).padStart(2, '0')}`))
const shopOf = (n) => data.shops.find((s) => s.id === product(n).shop_id)
const one = await Page.open(9351, 'browser-1')
const two = await Page.open(9352, 'browser-2')
const state = {}

if (want('H'))
  await journey('H first-time tour', async () => {
    await one.login(U('buyer-c'), { guides: false })
    await one.wait("!!document.querySelector('#guide-welcome')", 'tour opens after sign-in')
    check(await one.evaluate("document.querySelector('#guide-welcome').contains(document.activeElement)"), 'focus is inside the tour')
    await one.shot('H-tour-step1')
    await one.click('[data-guide-next]')
    check((await one.text('#guide-welcome')).includes('Bước 2 / 3'), 'step 2')
    // Not finished: a new page view opens it again.
    await one.goto('/products')
    await one.wait("!!document.querySelector('#guide-welcome')", 'tour again on the next page view')
    await one.click('[data-guide-skip]')
    await one.wait("!document.querySelector('#guide-welcome')", 'tour closed by Bỏ qua')
    await one.goto('/')
    check(!(await one.exists('#guide-welcome')), 'tour stays closed after skipping')
    // Replay from the account menu.
    await one.evaluate("(document.querySelector('.marketplace-account').setAttribute('open',''), true)")
    await one.clickText('Xem lại hướng dẫn', '.marketplace-account-menu')
    await one.wait("!!document.querySelector('#guide-welcome')", 'tour replayed')
    await one.evaluate("(document.querySelector('#guide-welcome').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true})), true)")
    await one.wait("!document.querySelector('#guide-welcome')", 'ESC closes the tour')
    // One-time note in the auction room.
    await one.goto(`/auctions/${data.live[0].id}`, 2500)
    await one.wait("!!document.querySelector('.first-time-note')", 'auction-room note')
    await one.shot('H-auction-note')
    await one.clickText('Bỏ qua', '.first-time-note')
    await one.goto(`/auctions/${data.live[0].id}`, 2500)
    check(!(await one.exists('.first-time-note')), 'note not shown again')
  })

if (want('A'))
  await journey('A guest → search/filter → detail → cart → voucher → COD', async () => {
    const item = product(10)
    await one.call('Network.clearBrowserCookies')
    await one.goto('/products')
    await one.evaluate('(localStorage.clear(), true)')
    await one.wait("document.querySelectorAll('[data-product]').length > 0", 'product list')
    await one.fill('.discovery-toolbar input[type="search"]', 'Sony')
    await one.fill('#condition', 'GOOD')
    await one.clickText('Tìm / Lọc', '.discovery-toolbar')
    await one.wait(`location.search.includes('Sony') && !!document.querySelector('[data-product="${item.id}"]')`, 'filtered result')
    check((await one.evaluate("document.querySelectorAll('[data-product]').length")) <= 3, 'filter narrows the list')
    await one.shot('A-search')
    await one.click(`[data-product="${item.id}"] h2 a`)
    await one.wait(`location.pathname === '/products/${item.slug}' && !!document.querySelector('.product-detail-side h1')`, 'product detail')
    await one.shot('A-detail')
    // A guest is sent to sign in, then comes back to the product.
    await one.clickText('Thêm vào giỏ', '.product-buy-bar')
    await one.wait("location.pathname === '/login'", 'guest redirected to login')
    await one.fill('#auth-email', U('buyer-b'))
    await one.fill('#auth-password', JSON.parse(await fs.readFile(new URL('./secret.json', import.meta.url), 'utf8')).password)
    await one.submit('.auth-form')
    await one.wait(`location.pathname === '/products/${item.slug}'`, 'back on the product after sign-in')
    await one.skipGuides(U('buyer-b'))
    await one.clickText('Thêm vào giỏ', '.product-buy-bar')
    await one.wait("document.body.innerText.includes('Đã thêm sản phẩm vào giỏ hàng')", 'added to cart')
    await one.goto('/cart')
    await one.wait(`document.body.innerText.includes(${JSON.stringify(item.name)})`, 'cart shows the product')
    await one.shot('A-cart')
    await one.clickText('Đặt hàng', 'main', 'a')
    await one.wait("location.pathname === '/checkout' && !!document.querySelector('#voucher-platform')", 'checkout')
    await one.fill('#voucher-platform', 'passlai10')
    await one.clickText('Áp dụng', '[data-platform-voucher]')
    await one.wait("document.querySelector('[data-checkout-discount]').innerText.includes('50.000')", 'platform voucher applied (10% capped at 50,000)')
    check((await one.text('[data-checkout-total]')).includes('3.450.000'), 'total after voucher is 3,450,000')
    await one.shot('A-checkout-voucher')
    await one.submit('form.buyer-two-column')
    await one.wait("/^\\/orders\\/\\d+$/.test(location.pathname)", 'order created')
    await one.wait("!!document.querySelector('[data-order-discount]')", 'order shows the discount')
    const text = await one.text('main')
    check(text.includes('PASSLAI10') && text.includes('3.450.000'), 'order keeps the code and discounted total')
    state.orderA = Number((await one.evaluate('location.pathname')).split('/').pop())
    await one.shot('A-order')
    check((await one.api('/api/v1/cart')).data.items.length === 0, 'cart is empty after ordering')
  })

if (want('B'))
  await journey('B buy now + shop voucher', async () => {
    const item = product(9)
    const other = product(14)
    await one.login(U('buyer-b'))
    // Something else stays in the cart.
    await one.goto(`/products/${other.slug}`)
    await one.clickText('Thêm vào giỏ', '.product-buy-bar')
    await one.wait("document.body.innerText.includes('Đã thêm sản phẩm vào giỏ hàng')", 'other product in cart')
    await one.goto(`/products/${item.slug}`)
    await one.click('[data-buy-now]')
    await one.wait("location.pathname === '/checkout' && location.search.includes('items=')", 'buy now opens checkout for one line')
    await one.wait("!!document.querySelector('[data-checkout-selection]')", 'selection notice')
    check((await one.evaluate("document.querySelectorAll('[data-checkout-shop]').length")) === 1, 'only the selected line is listed')
    await one.fill(`[data-shop-voucher="${item.shop_id}"] input`, 'CONGNGHE20K')
    await one.clickText('Áp dụng', `[data-shop-voucher="${item.shop_id}"]`)
    await one.wait("!!document.querySelector('[data-shop-discount]')", 'shop voucher applied')
    check((await one.text('[data-checkout-total]')).includes('1.180.000'), 'total 1,200,000 − 20,000')
    await one.shot('B-buy-now-checkout')
    await one.submit('form.buyer-two-column')
    await one.wait("/^\\/orders\\/\\d+$/.test(location.pathname)", 'order created')
    await one.wait("!!document.querySelector('[data-part-discount]')", 'shop discount on the order')
    check((await one.text('[data-part-discount]')).includes('CONGNGHE20K'), 'shop code stored on the order')
    state.orderB = Number((await one.evaluate('location.pathname')).split('/').pop())
    await one.shot('B-order')
    const cart = (await one.api('/api/v1/cart')).data
    check(cart.items.length === 1 && cart.items[0].product.id === String(other.id), 'the other product is still in the cart')
  })

export { one, two, state, U, product, shopOf, want }
