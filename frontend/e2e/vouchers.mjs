// Voucher management screens (seller and admin) on the isolated stack.
import process from 'node:process'
import { Page, report, journey, check, php } from './lib.mjs'
const U = (key) => `c1-${key}@example.test`
const one = await Page.open(9351, 'browser-1')
await journey('V voucher management screens', async () => {
  const code = 'E2E' + Date.now().toString().slice(-6)
  await one.login(U('seller-1'))
  await one.goto('/seller/vouchers', 2500)
  await one.wait("!!document.querySelector('[data-voucher]')", 'seller sees the shop voucher')
  check((await one.text('main')).includes('CONGNGHE20K'), 'demo shop voucher listed')
  await one.shot('V-seller-vouchers')
  await one.click('[data-voucher-create]')
  await one.wait("!!document.querySelector('#voucher-dialog')", 'create dialog')
  await one.fill('#voucher-code', code)
  await one.fill('#voucher-type', 'PERCENT')
  await one.fill('#voucher-value', '15')
  await one.fill('#voucher-max', '30000')
  await one.fill('#voucher-min', '100000')
  await one.fill('#voucher-limit', '20')
  await one.fill('#voucher-start', '2026-10-14T00:00')
  await one.fill('#voucher-end', '2026-12-31T23:59')
  await one.shot('V-voucher-dialog')
  await one.submit('#voucher-form')
  await one.wait("!document.querySelector('#voucher-dialog')", 'voucher saved')
  check(php(`echo DB::table('vouchers')->where('code', '${code}')->value('scope').'|'.DB::table('vouchers')->where('code', '${code}')->value('type');`) === 'SHOP|PERCENT', 'voucher stored for the shop')
  await one.clickText('Tắt mã', `[data-voucher="${php(`echo DB::table('vouchers')->where('code', '${code}')->value('id');`)}"]`)
  await one.wait(`document.querySelector('main').innerText.includes('Đã tắt mã.')`, 'voucher switched off')
  check(php(`echo DB::table('vouchers')->where('code', '${code}')->value('status');`) === 'INACTIVE', 'voucher is INACTIVE')
  await one.login(U('admin'))
  await one.goto('/admin/vouchers', 2500)
  await one.wait("document.querySelectorAll('[data-voucher]').length >= 3", 'admin sees all vouchers')
  const text = await one.text('main')
  check(text.includes('PASSLAI10') && text.includes('Chỉ xem'), 'platform voucher editable, shop vouchers read-only')
  await one.shot('V-admin-vouchers')
})
console.log(JSON.stringify({ journeys: report.journeys, overflow: Object.entries(report.shots).filter(([, v]) => v !== 'ok'), errors: report.errors }))
one.close()
process.exit(0)
